/**
 * Node directory layout and the generated Python entry program.
 *
 * The node's own source is written verbatim to `node_main.py`; the runner adds
 * a separate wrapper that owns stdin, the result line, and the exit codes. Two
 * layers of framing live here. The result is printed as one line prefixed by
 * {@link RESULT_SENTINEL} so a truncated log can never swallow it, and
 * `json.dumps(..., ensure_ascii=True)` keeps that line ASCII even when the
 * node's value is Chinese text or an emoji on a host whose default stdio
 * encoding is not UTF-8.
 *
 * @module @metaworkflow/workflow-python-runner/wrapper
 */

import { join } from 'node:path'
import { PythonRunnerError } from './errors.ts'
import { RESULT_SENTINEL } from './output.ts'

/** File the node's own module source is written to. */
export const NODE_SOURCE_FILE_NAME = 'node_main.py'

/** File the generated entry program is written to. */
export const WRAPPER_FILE_NAME = 'node_runner.py'

/** Directory inside a project that holds every node. */
export const NODES_DIRECTORY_NAME = 'nodes'

/** Maximum characters of a node id, so one id cannot outgrow a Windows path. */
export const MAX_NODE_ID_LENGTH = 128

/** Maximum characters of a project directory; Windows rejects a longer process working directory. */
export const MAX_PROJECT_PATH_LENGTH = 200

/** Prefix of the Python function each node module exports. */
const NODE_FUNCTION_PREFIX = 'nodemain_'

/**
 * Node ids become one directory name and one Python identifier, so only
 * alphanumerics, `.`, `_`, and `-` are accepted, and the first character must
 * be alphanumeric: no id can address a directory outside the project.
 */
const NODE_ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*$/u

/**
 * Refuse a project directory that a Windows process cannot use as its working directory.
 * @param projectDir - project directory the caller addressed.
 * @returns nothing.
 * @throws {@link PythonRunnerError} `project/path-too-long` above {@link MAX_PROJECT_PATH_LENGTH} characters.
 */
export function assertProjectPath(projectDir: string): void {
  if (projectDir.length > MAX_PROJECT_PATH_LENGTH) {
    throw new PythonRunnerError('project/path-too-long', `project directory "${projectDir}" is ${String(projectDir.length)} characters; ${String(MAX_PROJECT_PATH_LENGTH)} is the maximum because Windows rejects a longer process working directory`)
  }
}

/**
 * Refuse a node id that cannot name one directory and one Python function.
 * @param nodeId - node id the caller addressed.
 * @returns nothing.
 * @throws {@link PythonRunnerError} `node/invalid-id` for a path separator, an empty id, or an over-long id.
 */
export function assertNodeId(nodeId: string): void {
  if (!NODE_ID_PATTERN.test(nodeId) || nodeId.length > MAX_NODE_ID_LENGTH) {
    throw new PythonRunnerError('node/invalid-id', `node id ${JSON.stringify(nodeId)} is not usable: it must match ${NODE_ID_PATTERN.source} and stay within ${String(MAX_NODE_ID_LENGTH)} characters`)
  }
}

/**
 * Absolute directory of one node inside its project.
 * @param projectDir - project directory that owns the node.
 * @param nodeId - node id.
 * @returns `<projectDir>/nodes/<nodeId>`.
 */
export function nodeDirectory(projectDir: string, nodeId: string): string {
  return join(projectDir, NODES_DIRECTORY_NAME, nodeId)
}

/**
 * Python identifier the wrapper imports from the node module.
 * @param nodeId - node id; every character outside `[A-Za-z0-9_]` becomes `_`.
 * @returns `nodemain_<id>`, the function the node source must define.
 */
export function nodeFunctionName(nodeId: string): string {
  return `${NODE_FUNCTION_PREFIX}${nodeId.replaceAll(/[^A-Za-z0-9_]/gu, '_')}`
}

/**
 * Generate the entry program for one node.
 *
 * The program reads JSON inputs from stdin, calls the node function, and
 * writes exactly one result line. A raised exception prints its traceback and
 * exits `1`; a non-`str` return or a `str` that is not JSON exits `2`.
 * @param functionName - node function the program imports.
 * @returns complete Python source, ASCII only.
 */
export function wrapperSource(functionName: string): string {
  return [
    '"""Node entry generated by the MetaWorkFlow Python runner."""',
    '',
    'import json',
    'import sys',
    'import traceback',
    '',
    `from node_main import ${functionName} as __mwf_node__`,
    '',
    `RESULT_SENTINEL = ${JSON.stringify(RESULT_SENTINEL)}`,
    '',
    '',
    'def __mwf_read_inputs__():',
    '    raw = sys.stdin.read()',
    '    if raw.strip() == "":',
    '        return {}',
    '    return json.loads(raw)',
    '',
    '',
    'def __mwf_main__():',
    '    try:',
    '        inputs = __mwf_read_inputs__()',
    '    except ValueError:',
    '        sys.stderr.write("node inputs are not valid JSON\\n")',
    '        return 2',
    '    try:',
    '        value = __mwf_node__(inputs)',
    '    except BaseException:',
    '        traceback.print_exc()',
    '        return 1',
    '    if not isinstance(value, str):',
    '        sys.stderr.write("node function must return a str holding JSON, got " + type(value).__name__ + "\\n")',
    '        return 2',
    '    try:',
    '        json.loads(value)',
    '    except ValueError:',
    '        sys.stderr.write("node function returned a str that is not JSON\\n")',
    '        return 2',
    '    sys.stdout.write(RESULT_SENTINEL + " " + json.dumps(value, ensure_ascii=True) + "\\n")',
    '    sys.stdout.flush()',
    '    return 0',
    '',
    '',
    'if __name__ == "__main__":',
    '    sys.exit(__mwf_main__())',
    '',
  ].join('\n')
}
